# hot dog vendor
# asks user for what type of hot dog they want and how many, then prints result

print("Welcome dog distribution system! ")
dog_type = input("please pick a dog! beef, premium, or polish? ")
if dog_type == "polish":
  print("polish one dollar extra")

# pick a dog amount, discount for multiple
num_of_dogs = int(input("how many dogs do you want? "))
if num_of_dogs > 1:
  print("multi dog discount")

print("Get ready for your" + " " + str(num_of_dogs) + " " + dog_type + "!")

# Example run 1
# inputs: beef, 1
# Output: get ready for your 1 beef!

